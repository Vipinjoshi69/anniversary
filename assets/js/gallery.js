const gallery = document.getElementById("gallery");
const galleryTrack = document.getElementById("galleryTrack");
const galleryDots = document.getElementById("galleryDots");
const galleryPrevBtn = document.getElementById("galleryPrev");
const galleryNextBtn = document.getElementById("galleryNext");
const galleryBackBtn = document.getElementById("galleryBackBtn");
const galleryCounter = document.getElementById("galleryCounter");

let galleryIndex = 0;
let galleryReachedEnd = false;

let galleryTouchStartX = 0;
let galleryTouchDeltaX = 0;

/*=========================================
    BUILD (runs once)
=========================================*/

function initGallery() {

    memoryPhotos.forEach((photo, i) => {

        const card = document.createElement("div");

        card.className = "polaroid";
        card.dataset.index = i;

        card.innerHTML = `
            <div class="polaroid-frame">
                <img src="${photo.src}" class="polaroid-photo" alt="${photo.caption}">
            </div>
            <div class="polaroid-caption">
                ${photo.date ? `<span class="polaroid-date">${photo.date}</span>` : ""}
                <span>${photo.caption}</span>
            </div>
        `;

        galleryTrack.appendChild(card);

        const dot = document.createElement("span");

        dot.className = "gallery-dot";
        dot.addEventListener("click", () => goToGallerySlide(i));

        galleryDots.appendChild(dot);

    });

    // Tap a photo for a true fullscreen view (reuses the WhatsApp image viewer)
    galleryTrack.addEventListener("click", (e) => {

        const frame = e.target.closest(".polaroid-frame");

        if (!frame) return;

        const img = frame.querySelector(".polaroid-photo");

        if (!img) return;

        if (typeof viewer !== "undefined") {

            viewer.classList.add("show");
            viewerImage.src = img.src;

        }

    });

    galleryPrevBtn.addEventListener("click", () => goToGallerySlide(galleryIndex - 1));
    galleryNextBtn.addEventListener("click", () => goToGallerySlide(galleryIndex + 1));
    galleryBackBtn.addEventListener("click", goHome);

    galleryTrack.addEventListener("touchstart", (e) => {

        galleryTouchStartX = e.touches[0].clientX;

    }, { passive: true });

    galleryTrack.addEventListener("touchmove", (e) => {

        galleryTouchDeltaX = e.touches[0].clientX - galleryTouchStartX;

    }, { passive: true });

    galleryTrack.addEventListener("touchend", () => {

        if (galleryTouchDeltaX < -50) goToGallerySlide(galleryIndex + 1);
        else if (galleryTouchDeltaX > 50) goToGallerySlide(galleryIndex - 1);

        galleryTouchDeltaX = 0;

    });

}

/*=========================================
    NAVIGATION
=========================================*/

function goToGallerySlide(index) {

    if (index < 0) index = 0;
    if (index > memoryPhotos.length - 1) index = memoryPhotos.length - 1;

    galleryIndex = index;

    galleryTrack.style.transform = `translateX(-${galleryIndex * 100}%)`;

    document.querySelectorAll(".gallery-dot").forEach((dot, i) => {

        dot.classList.toggle("active", i === galleryIndex);

    });

    galleryPrevBtn.disabled = galleryIndex === 0;
    galleryNextBtn.disabled = galleryIndex === memoryPhotos.length - 1;

    if (galleryCounter) {

        galleryCounter.textContent = `${galleryIndex + 1} / ${memoryPhotos.length}`;

    }

    // Chapter complete once the last memory has been seen
    if (galleryIndex === memoryPhotos.length - 1 && !galleryReachedEnd) {

        galleryReachedEnd = true;

        if (typeof unlockApp === "function") unlockApp("letter");

    }

}

/*=========================================
    SHOW / HIDE
=========================================*/

function showGallery() {

    gallery.classList.add("show");
    goToGallerySlide(0);
    playBg2();

}

function hideGallery() {

    gallery.classList.remove("show");
    pauseBg2();

    document.querySelectorAll(".polaroid").forEach(p => {

        p.style.transform = "";

    });

}

document.addEventListener("DOMContentLoaded", initGallery);

/*=========================================
    PARALLAX
    A few degrees of tilt toward the cursor,
    applied to the polaroid wrapper (not the
    frame itself, since the frame already has
    its own float/rotate animation running -
    same technique used in the First Meet
    rain scene).
=========================================*/

document.addEventListener("mousemove", (e) => {

    if (!gallery.classList.contains("show")) return;

    const relX = (e.clientX / window.innerWidth - 0.5) * 2;
    const relY = (e.clientY / window.innerHeight - 0.5) * 2;

    document.querySelectorAll(".polaroid").forEach(p => {

        p.style.transform = `rotateY(${relX * 4}deg) rotateX(${relY * -4}deg)`;

    });

});
